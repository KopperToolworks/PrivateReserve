inline bool docsQrModule(int x, int y) {
  if (x < 0 || y < 0 || x >= kDocsQrSize || y >= kDocsQrSize) {
    return false;
  }
  const int i = y * kDocsQrSize + x;
  const uint8_t b = pgm_read_byte(&kDocsQrBits[i >> 3]);
  return (b >> (7 - (i & 7))) & 1;
}

